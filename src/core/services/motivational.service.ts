export function getDailyPhrase(offsetDays: number = 0): MotivationalPhrase {
  // 1. Agrupar frases dinámicamente
  const forja: MotivationalPhrase[] = [];
  const historia: MotivationalPhrase[] = [];
  const refran: MotivationalPhrase[] = [];
  const famosa: MotivationalPhrase[] = [];

  phrases.forEach(p => {
    const author = p.author.toLowerCase();
    if (author === 'forja') forja.push(p);
    else if (author.includes('historia')) historia.push(p);
    else if (author.includes('refrán')) refran.push(p);
    else famosa.push(p);
  });

  // Filtramos categorías vacías (por precaución) y fijamos un orden de rotación
  // Orden: Famosa -> Forja -> Historia -> Refrán -> Forja -> Famosa... etc.
  const categories = [famosa, forja, historia, refran, forja].filter(c => c.length > 0);

  const now = new Date();
  // Compensamos la zona horaria para que 'medianoche UTC' equivalga a 'medianoche local'
  const offsetMs = now.getTimezoneOffset() * 60 * 1000;
  // Tiempo ajustado donde el día cambia a las 5:30 AM hora local
  const shiftMs = 5.5 * 60 * 60 * 1000;
  const shiftedTime = now.getTime() - offsetMs - shiftMs;

  // Calculamos el índice base del día y le sumamos el offset manual
  const dayIndex = Math.abs(Math.floor(shiftedTime / 86400000)) + offsetDays;

  // Selección de categoría Round-Robin
  const categoryIndex = dayIndex % categories.length;
  const selectedCategory = categories[categoryIndex];
  
  // Selección de frase (avanza a medida que pasan las semanas)
  const phraseIndex = Math.floor(dayIndex / categories.length) % selectedCategory.length;
  
  return selectedCategory[phraseIndex];
}